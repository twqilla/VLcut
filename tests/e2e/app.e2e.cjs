    check('clicking the text in the preview selects it', (await win.locator('.clip-text.selected').count()) === 1)
    await win.mouse.dblclick(cv.x + cv.width / 2, cv.y + cv.height * 0.16)
    await win.waitForSelector('.text-editor', { timeout: 5000 })
    check('double-clicking the text in the preview opens the editor', true)
    await win.click('button[aria-label="Close text editor"]')
