    check('the menu does what it says', (await win.locator('.clip-text').count()) === before + 1 && (await win.locator('.context-menu').count()) === 0)
    await win.locator('.clip-text').first().click({ button: 'right' })
    await win.click('.context-menu button:has-text("Delete")')
    await win.waitForFunction((n) => document.querySelectorAll('.clip-text').length === n, before, { timeout: 5000 })
    check('Delete in the menu removes the clip', (await win.locator('.clip-text').count()) === before)
    // A spoken voice-over from the voices that come with the computer.
