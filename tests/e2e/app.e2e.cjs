/** Stands in for a local Ollama server so the vision-model path can be tested without a real model. */
function fakeOllama() {
  const http = require('node:http')
  const server = http.createServer((req, res) => {
    let body = ''
    req.on('data', (d) => (body += d))
    req.on('end', () => {
      res.setHeader('Content-Type', 'application/json')
      if (req.url === '/api/tags') return res.end(JSON.stringify({ models: [{ name: 'llava:7b' }] }))
      const parsed = JSON.parse(body || '{}')
      if (/^Translate these subtitle lines/.test(parsed.prompt ?? '')) {
        const lines = JSON.parse(parsed.prompt.trim().split('\n').pop())
        return res.end(JSON.stringify({ response: JSON.stringify(lines.map((l) => `ES: ${l}`)) }))
      }
      res.end(JSON.stringify({ response: parsed.images?.length ? 'A tall glass building at dusk.' : '[]' }))
    })
  })
  return new Promise((resolve) => server.listen(0, '127.0.0.1', () => resolve(server)))
}

