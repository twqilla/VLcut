    await win.click('.modal footer button:has-text("Export")')
    await win.waitForSelector('.export-status.done, .export-status.error', { timeout: 240000 })
    const iFrames = execFileSync('ffprobe', ['-v', 'error', '-select_streams', 'v', '-show_entries', 'frame=pict_type', '-of', 'csv=p=0', regionOut]).toString().split('\n').filter((x) => x.trim() === 'I').length
